function Format-CoverPage {
    param(
        $Document
    )

    $resumeHeading = Get-ParagraphByExactText -Document $Document -Text 'Резюме' -RequiredStyleName 'Heading 1'

    for ($i = 1; $i -le $Document.Paragraphs.Count; $i++) {
        $paragraph = $Document.Paragraphs.Item($i)
        if ($paragraph.Range.Start -ge $resumeHeading.Range.Start) {
            break
        }

        $text = Normalize-WordText $paragraph.Range.Text
        if ([string]::IsNullOrWhiteSpace($text)) {
            continue
        }

        $paragraph.Range.ParagraphFormat.Alignment = 1
        $paragraph.Range.ParagraphFormat.FirstLineIndent = 0
        $paragraph.Range.Font.Name = 'Times New Roman'
        $paragraph.Range.Font.Bold = 0
        $paragraph.Range.Font.Italic = 0
        $paragraph.Range.Font.Size = 12
        $paragraph.Range.ParagraphFormat.SpaceBefore = 0
        $paragraph.Range.ParagraphFormat.SpaceAfter = 6

        switch ($text) {
            'ДИПЛОМЕН ПРОЕКТ' {
                $paragraph.Range.Font.Size = 18
                $paragraph.Range.Font.Bold = -1
                $paragraph.Range.ParagraphFormat.SpaceAfter = 12
            }
            'НА ТЕМА' {
                $paragraph.Range.Font.Size = 14
                $paragraph.Range.Font.Bold = -1
            }
            '„SchoolAccessControlDocumentation“' {
                $paragraph.Range.Font.Size = 16
                $paragraph.Range.Font.Bold = -1
                $paragraph.Range.Font.Italic = -1
                $paragraph.Range.ParagraphFormat.SpaceAfter = 18
            }
            'Ученици:' {
                $paragraph.Range.Font.Bold = -1
                $paragraph.Range.ParagraphFormat.SpaceBefore = 12
            }
            'Клас: 12ж' {
                $paragraph.Range.ParagraphFormat.SpaceBefore = 6
            }
            'гр. Пловдив, 2026' {
                $paragraph.Range.ParagraphFormat.SpaceBefore = 18
            }
        }
    }
}

function Remove-StandaloneSlashParagraphs {
    param($Document)

    for ($i = $Document.Paragraphs.Count; $i -ge 1; $i--) {
        $paragraph = $Document.Paragraphs.Item($i)
        $text = Normalize-WordText $paragraph.Range.Text
        if ($text -eq '/') {
            $paragraph.Range.Delete() | Out-Null
        }
    }
}

function Format-CaptionParagraphs {
    param($Document)

    for ($i = 1; $i -le $Document.Paragraphs.Count; $i++) {
        $paragraph = $Document.Paragraphs.Item($i)
        $text = Normalize-WordText $paragraph.Range.Text
        if ($text -like 'Фигура *' -or $text -like 'Таблица *') {
            $paragraph.Range.ParagraphFormat.Alignment = 1
            $paragraph.Range.ParagraphFormat.FirstLineIndent = 0
            $paragraph.Range.Font.Name = 'Times New Roman'
            $paragraph.Range.Font.Size = 11
            $paragraph.Range.Font.Italic = -1
            $paragraph.Range.Font.Bold = 0
            $paragraph.Range.ParagraphFormat.SpaceBefore = 6
            $paragraph.Range.ParagraphFormat.SpaceAfter = 6
        }
    }
}

