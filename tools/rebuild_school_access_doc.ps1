function Normalize-WordText {
    param([string]$Text)

    if ($null -eq $Text) {
        return ''
    }

    return (($Text -replace '[\r\a\f\v]+', ' ' -replace '\s+', ' ').Trim())
}

function Get-ParagraphByExactText {
    param(
        $Document,
        [string]$Text,
        [string]$RequiredStyleName
    )

    for ($i = 1; $i -le $Document.Paragraphs.Count; $i++) {
        $paragraph = $Document.Paragraphs.Item($i)
        $styleName = $paragraph.Range.Style.NameLocal
        if ((Normalize-WordText $paragraph.Range.Text) -eq $Text -and ([string]::IsNullOrWhiteSpace($RequiredStyleName) -or $styleName -eq $RequiredStyleName)) {
            return $paragraph
        }
    }

    if ([string]::IsNullOrWhiteSpace($RequiredStyleName)) {
        throw "Paragraph not found: $Text"
    }

    throw "Paragraph not found: $Text [$RequiredStyleName]"
}

function Add-ParagraphBlock {
    param(
        $Document,
        $Selection,
        [string]$Text,
        [string]$StyleName = 'Normal',
        [ValidateSet('Left', 'Center', 'Right', 'Justify')]
        [string]$Alignment = 'Justify',
        [switch]$NoFirstLineIndent,
        [nullable[int]]$FontSize,
        [switch]$Bold,
        [switch]$Italic,
        [nullable[double]]$SpaceBefore,
        [nullable[double]]$SpaceAfter
    )

    $start = $Selection.Range.Start
    $Selection.TypeText($Text)
    $Selection.TypeParagraph()
    $end = $Selection.Range.Start
    $range = $Document.Range($start, [Math]::Max($start, $end - 1))

    if ($StyleName) {
        $range.Style = $StyleName
    }

    switch ($Alignment) {
        'Left' { $range.ParagraphFormat.Alignment = 0 }
        'Center' { $range.ParagraphFormat.Alignment = 1 }
        'Right' { $range.ParagraphFormat.Alignment = 2 }
        'Justify' { $range.ParagraphFormat.Alignment = 3 }
    }

    if ($NoFirstLineIndent) {
        $range.ParagraphFormat.FirstLineIndent = 0
    }

    if ($FontSize.HasValue) {
        $range.Font.Size = $FontSize.Value
    }

    $range.Font.Bold = $(if ($Bold) { -1 } else { 0 })
    $range.Font.Italic = $(if ($Italic) { -1 } else { 0 })

    if ($SpaceBefore.HasValue) {
        $range.ParagraphFormat.SpaceBefore = $SpaceBefore.Value
    }

    if ($SpaceAfter.HasValue) {
        $range.ParagraphFormat.SpaceAfter = $SpaceAfter.Value
    }

    return $range
}

function Add-TableBlock {
    param(
        $Document,
        $Selection,
        [string]$Caption,
        [string[]]$Headers,
        [object[][]]$Rows
    )

    Add-ParagraphBlock -Document $Document -Selection $Selection -Text $Caption -StyleName 'Normal' -Alignment 'Center' -NoFirstLineIndent -FontSize 11 -Italic -SpaceBefore 6 -SpaceAfter 6 | Out-Null

    $rowCount = $Rows.Count + 1
    $columnCount = $Headers.Count
    $table = $Document.Tables.Add($Selection.Range, $rowCount, $columnCount)

    try {
        $table.Style = 'Table Grid'
    } catch {
    }

    try {
        $table.Range.Style = 'Normal'
    } catch {
    }

    $table.Range.Font.Name = 'Times New Roman'
    $table.Range.Font.Size = 11
    $table.Range.ParagraphFormat.SpaceAfter = 0
    $table.Range.ParagraphFormat.SpaceBefore = 0
    $table.Rows.Alignment = 0
    $table.Borders.Enable = 1

    for ($c = 1; $c -le $columnCount; $c++) {
        $cellRange = $table.Cell(1, $c).Range
        try { $cellRange.Style = 'Normal' } catch {}
        $cellRange.Text = [string]$Headers[$c - 1]
        $cellRange.Bold = -1
        $cellRange.ParagraphFormat.Alignment = 1
        $cellRange.ParagraphFormat.FirstLineIndent = 0
    }

    for ($r = 0; $r -lt $Rows.Count; $r++) {
        for ($c = 0; $c -lt $columnCount; $c++) {
            $cellRange = $table.Cell($r + 2, $c + 1).Range
            try { $cellRange.Style = 'Normal' } catch {}
            $cellRange.Text = [string]$Rows[$r][$c]
            $cellRange.Bold = 0
            $cellRange.ParagraphFormat.Alignment = 0
            $cellRange.ParagraphFormat.FirstLineIndent = 0
        }
    }

    try {
        $table.AutoFitBehavior(2) | Out-Null
    } catch {
    }

    $afterRange = $Document.Range($table.Range.End, $table.Range.End)
    $afterRange.InsertParagraphAfter()
    $Selection.SetRange($afterRange.End, $afterRange.End)
}

function Add-Blocks {
    param(
        $Document,
        $Selection,
        [object[]]$Blocks
    )

    foreach ($block in $Blocks) {
        switch ($block.Type) {
            'Heading1' {
                Add-ParagraphBlock -Document $Document -Selection $Selection -Text $block.Text -StyleName 'Heading 1' -Alignment 'Left' -NoFirstLineIndent -Bold -SpaceBefore 12 -SpaceAfter 6 | Out-Null
            }
            'Heading2' {
                Add-ParagraphBlock -Document $Document -Selection $Selection -Text $block.Text -StyleName 'Heading 2' -Alignment 'Left' -NoFirstLineIndent -Bold -SpaceBefore 12 -SpaceAfter 6 | Out-Null
            }
            'Heading3' {
                Add-ParagraphBlock -Document $Document -Selection $Selection -Text $block.Text -StyleName 'Heading 3' -Alignment 'Left' -NoFirstLineIndent -Bold -SpaceBefore 8 -SpaceAfter 4 | Out-Null
            }
            'Body' {
                Add-ParagraphBlock -Document $Document -Selection $Selection -Text $block.Text -StyleName 'Normal' -Alignment 'Justify' -SpaceBefore 0 -SpaceAfter 0 | Out-Null
            }
            'Line' {
                Add-ParagraphBlock -Document $Document -Selection $Selection -Text $block.Text -StyleName 'Normal' -Alignment 'Left' -NoFirstLineIndent -SpaceBefore 0 -SpaceAfter 0 | Out-Null
            }
            'Caption' {
                Add-ParagraphBlock -Document $Document -Selection $Selection -Text $block.Text -StyleName 'Normal' -Alignment 'Center' -NoFirstLineIndent -FontSize 11 -Italic -SpaceBefore 6 -SpaceAfter 6 | Out-Null
            }
            'Table' {
                Add-TableBlock -Document $Document -Selection $Selection -Caption $block.Caption -Headers $block.Headers -Rows $block.Rows
            }
            default {
                throw "Unknown block type: $($block.Type)"
            }
        }
    }
}

function Rename-HeadingText {
    param(
        $Document,
        [string]$OldText,
        [string]$NewText,
        [string]$StyleName = 'Heading 1'
    )

    $paragraph = Get-ParagraphByExactText -Document $Document -Text $OldText -RequiredStyleName $StyleName
    $range = $paragraph.Range.Duplicate
    $range.End = $range.End - 1
    $range.Text = $NewText
}

